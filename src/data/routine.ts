export function exercisesForDay(day: 1 | 2 | 3 | 4): Exercise[] {
  return ROUTINE.filter((e) => e.day === day).sort((a, b) => {
    if (a.order !== b.order) return a.order - b.order;
    return (a.supersetLabel ?? "").localeCompare(b.supersetLabel ?? "");
  });
}

export function exerciseById(id: string): Exercise | undefined {
  return ROUTINE.find((e) => e.id === id);
}
